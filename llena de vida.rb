Pre-race Brief
This went very well. My main question was if we could leave our bag on the bus at the start line, and that was
answered. This allowed me to save on a hotel for Friday and Saturday night. This made cost and logistics so much easier
for me. I stayed at Posada 1914 Sunday night and Nicholas (working the front desk) asked what was wrong with me :)
I told him I ran El Reto, and he said 3 of his friends ran the 105k! So we talked about that for a long time.

Packet Pickup
Went well, dropped my bag, grabbed the swag, very fast everyone was super friendly and helpful. I was looking for
non-caffinated gels and recieved several ideas.

Start
I love the evening start. I spoke with other runners who did the 161k race during the morning start a couple years ago,
and they had heat exhaustion or heat stroke, and there was a huge DNF. So I think the night start
was perfect. The first 3 or 4 K allowed us to split into smaller groups. We all found a good pace, and
there were 3 distinct groups as we entered the forest. I was in the middle group. Some races have thin
trails and runners trying to pass and it gets really congested when you hit the trail. I think the start
had a good amount of road allowing us to find our own pace, and I never felt rushed or held back.

The initial aid stations went well(they all went well, the first few are always the most rushed). All
the runners still had energy and moved quick, and the volunteers were calm, smooth, and fast.

The Mud
Approaching Gatun, all the way past Tres Hermanas, the mud was serious. I assume this will be the primary feedback.
In my opinion, there is no more that can be done here. I watched youtube videos which talked about the mud. I knew
the mud was going to be worse this year from the pre-race briefing. Where I'm from, I could not have prepared or
trained myself for this kind of mud. I chose not to bring poles even though I knew about the mud. Its a 161k race
through the jungle, it will be wet and muddy :)

The work to harden the sides of the road made all the difference. We formed lines finding the right footing. Faster
runners lead the way. Without the work on the side of the roads, some sections may have been unpassable. Thank you
so much, and thanks to the local communities for this work!

Ideas for the mud are really mental:
 * Expect mud up to you knees, possibly higher if you step in the wrong spot
 * Don't have expectations for pace or time through the mud, be ready to recalculate when you reach 3Hermanas
 * Stay in a group through the mud, follow the path of others
 * Don't change socks until Gatun, and then 3Hermanas. Just be wet and muddy :)
 * Wear gloves because there will be barbed wire and you will be grabbing trees and falling over and it is
   easy to cut yourself

 Gatun to 3Hermanas
 This was mostly solo. Passing a couple folks, then they'd pass me. Just moving through to 3Hermanas. I saw an
 armadillo but I didn't get my phone out in time before he ran away.

 3Hermanas to El Valle
 I've never had humidity so thick that I couldn't see. My headlamp reflected right back at me. The climbing really
 beings here. I highly recommend coming through this section as the sun rises. You get amazing views of the forest.

 I really enjoyed the single track jungle descending into El Valle. It doesn't look possible to climb Cerro Gaital,
 but that would be awesome if there is a trail (we have climbed so much anyway, why not). It was day, I could really
 feel the forest. I'm sure there was wildlife everywhere. I took my time through the single track.

 While the jungle approach to El Valle was one of my favorite sections of the race, coming into El Valle was
 the dark period for me. I had mentally quit some time after 3Hermanas. I had decided to get my shoes at El Valle,
 and call it quits. After the single track, when I turned onto the main road, I saw a sign making me think
 the aid station was right down the street, but it was still ~4k. The blisters on my toes were popping as I ran to
 the station.

 I spent 30 minutes at the El Valle station. The volunteers told me I was in top 10. They asked how my watch battery
 was (it was not good) and helped me get my watch charging as I drank broth. They gave my feet some first aid. This
 station really recharged me. I was ready to quit as I came into the station, and I left the station excited to keep
 going.

 The Beach
 At the final aid station they said nobody else in my age group had passed. So it felt like I was racing. I would
 turn off my headlamp and then look behind me to see if anyone was approaching :) After the highway, entering the
 beach forest was a little confusing. I think it was well marked, I just think I had been running for 30 hours and
 was not at full capacity. The beach felt like it went on forever. It was the final 7k, so that makes sense.
 I got a little turned around as I was entering the parking lot areas.

 Marking
 The course was amazingly well marked. I went off course 3 times. Each time I missed a turn and my watch beeped at
 me. One of the times I ran to El Rio Indio, and turned back to take a bridge. The other two times I was just
 lost in thought running and then my watch beeped.

 What did I learn?
 General:
 * Move slow and consistent. Less time sitting is more time moving at a leisurely pace.
 * Recognize the dark times. Know they end.
 * There is so much more in you than you previously knew
 * You can go so far by just putting one foot in front of the other

 Specific:
 * More socks
 * Repeat your plan as you approach each aid station, otherwise you will forget what is most important
   and go with the flow.
 * When it hurts to walk, run
 * 

 What I liked
  * Panama in general:
    * Very easy to get around, uber was easy, everything was walking distance.
    * Lots to do. Trails very close to the city, canal tours and Gamboa tours
    * Lots to eat.
    * Lots of English, dollars are accepted.
  * I got to meet so many people who are so nice and passionate about a great event
  * I saw so many places that I would never have seen or experienced in any other way
  * Logistics was perfect. The buses were great. Being able to send my backpack to the finish on the bus was perfect. 
  * Course markings were fantastic. 
  * I liked the night/day/night format. I would be very worried about heat if it were day/night/day.

Challenges
  * I get nervous about food, so I brought a sandwich with me to Colon. I never ate it, but I didn't know
    the food situation so I wanted to be prepared.
  * I didn't want to bring gels with me because sometimes they get crushed and pop open in transit.
    I found some Hammer nutrition at a Tennis store! I don't often run with caffinee, so one of my
    challenges was finding non-caffinated gels. I did, it worked well.

Improvements
